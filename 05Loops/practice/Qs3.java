public class Qs3 {
    public static void main(String[] args){
        //Even Number or Odd number 
        int number = 100;
        for(int i=1; i<=number; i++){
            if(i%2==0){
                System.out.println("Even number : "+i);
            } else{
                System.out.println("Odd Number : "+i);
            }
        }
    }
}
